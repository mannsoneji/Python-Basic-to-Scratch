# 1. print() Function
# What is print()?

# print() is used to display output on the screen.

# It is the most basic way for a Python program to communicate with the user.

# Why do we use it?

# We use print() to:

# show messages,
# display results,
# debug programs,
# check values.

# Syntax
# print(value)

# Example
print("Hello, World!")

# output = Hello, World!
